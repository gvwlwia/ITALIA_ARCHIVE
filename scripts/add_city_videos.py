@transaction.atomic
def add_city_videos():
    """Создаёт видеоматериалы и связывает их с соответствующими городами."""

    added = 0

    for city_id, title, video_id, summary in CITY_VIDEOS:

        # Находим город по его идентификатору.
        city = City.objects.get(pk=city_id)

        # Формируем адреса видеоматериала.
        youtube_url = f'https://www.youtube.com/watch?v={video_id}'
        embed_url = f'https://www.youtube.com/embed/{video_id}'

        # Создаём общую запись видеоматериала.
        content_item, created = ContentItem.objects.update_or_create(
            slug=f'city-video-{city_id}',
            defaults={
                'content_type': 'video',
                'title': title,
                'summary': summary,
                'source_url': youtube_url,
                'source_name': 'YouTube',
                'status': 'published',
            }
        )

        # Добавляем или обновляем видеоссылку.
        Media.objects.update_or_create(
            content_item=content_item,
            defaults={
                'media_type': 'video',
                'file_url': embed_url,
                'caption': title,
            }
        )

        # Связываем видеоматериал с городом.
        CityContentLink.objects.get_or_create(
            city=city,
            content_item=content_item,
        )

        if created:
            added += 1

        print(f'Готово: {city.name} — {title}')

    print()
    print(f'Обработка завершена. Новых видеоматериалов: {added}')
    print(f'Всего обработано городов: {len(CITY_VIDEOS)}')


add_city_videos()
